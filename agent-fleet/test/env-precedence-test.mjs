import assert from 'node:assert/strict';
import { mkdtempSync, mkdirSync, writeFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { loadRuntimeEnv } from '../src/env.mjs';
const root = mkdtempSync(join(tmpdir(), 'fleet-env-'));
const pkg = join(root, 'pkg'), home = join(root, 'home');
mkdirSync(pkg); mkdirSync(join(home, '.agent-fleet'), {recursive:true});
writeFileSync(join(pkg, '.env'), 'FLEET_CODE_CAPACITY=16\nFLEET_TEST_DEFAULT=package\nFLEET_TEST_SHELL=package\n');
writeFileSync(join(home, '.agent-fleet', '.env'), 'FLEET_CODE_CAPACITY=32\nFLEET_TEST_SHELL=user\n');
const oldCapacity = process.env.FLEET_CODE_CAPACITY;
delete process.env.FLEET_CODE_CAPACITY;
process.env.FLEET_TEST_SHELL = 'shell';
loadRuntimeEnv(pkg, home);
assert.equal(process.env.FLEET_CODE_CAPACITY, '32');
assert.equal(process.env.FLEET_TEST_DEFAULT, 'package');
assert.equal(process.env.FLEET_TEST_SHELL, 'shell');
if (oldCapacity === undefined) delete process.env.FLEET_CODE_CAPACITY; else process.env.FLEET_CODE_CAPACITY = oldCapacity;
delete process.env.FLEET_TEST_DEFAULT; delete process.env.FLEET_TEST_SHELL;
rmSync(root,{recursive:true,force:true});
console.log('PASS shell > user config > package defaults');
