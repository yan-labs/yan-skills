import assert from 'node:assert/strict';
import { mkdtempSync, mkdirSync, writeFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
const root = mkdtempSync(join(tmpdir(), 'status-index-'));
process.env.HOME = root;
process.env.AGENT_FLEET_RUNS_DIR = join(root, 'runs');
mkdirSync(process.env.AGENT_FLEET_RUNS_DIR);
const { indexedRecords } = await import('../src/status-index.mjs');
const names = ['old.json', 'parked.json'];
const old = { runId: 'old', detach: true, status: 'done', finishedAt: '2000-01-01T00:00:00Z', startedAt:'1999-12-31T00:00:00Z', briefPath:'/test/review.md', secret:'not cached' };
const parked = { runId: 'parked', detach: true, status:'parked', startedAt:'2000-01-01T00:00:00Z' };
const put = (n, value) => writeFileSync(join(process.env.AGENT_FLEET_RUNS_DIR,n),JSON.stringify(value));
put(names[0],old); put(names[1],parked);
let reads=[];
const read = n => { reads.push(n); return JSON.parse((awaitlessRead(join(process.env.AGENT_FLEET_RUNS_DIR,n)))); };
const { readFileSync } = await import('node:fs');
const awaitlessRead = p => readFileSync(p,'utf8');
indexedRecords(names,read,'detached');
reads=[];
const cached=indexedRecords(names,read,'detached');
assert.deepEqual(reads,['parked.json'], 'old terminal cached, long parked still read');
assert.equal(cached[0].briefPath,old.briefPath);
assert.equal(cached[0].secret,undefined);
put(names[0],{...old,status:'running'});
reads=[];
assert.equal(indexedRecords(names,read,'detached')[0].status,'running');
assert(reads.includes('old.json'),'changed terminal invalidates index');
rmSync(root,{recursive:true,force:true});
console.log('status index: old terminal cache, long parked, mutation invalidation OK');
