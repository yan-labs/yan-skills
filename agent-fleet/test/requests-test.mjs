import assert from 'node:assert/strict';
import { mkdtempSync, writeFileSync, appendFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
const root = mkdtempSync(join(tmpdir(), 'fleet-requests-'));
process.env.AGENT_FLEET_RUNS_DIR = root;
const { pendingFor, linkedReview, records } = await import('../src/requests.mjs');
const { localCondition } = await import('../src/yield.mjs');
const put = (name, obj) => writeFileSync(join(root, name), JSON.stringify(obj));
const maker = {detach:true,runId:'maker',name:'work',status:'running'};
put('maker.json',maker);
const ask = {id:'a',runId:'maker',kind:'resource',text:'资源',at:'2026-01-01T00:00:00.000Z'};
writeFileSync(join(root,'maker.asks'),JSON.stringify(ask)+'\n');
assert.equal(pendingFor('maker').length,1);
writeFileSync(join(root,'maker.inbox'),JSON.stringify({type:'say',at:'2026-01-01T00:00:01.000Z'})+'\n');
assert.equal(pendingFor('maker').length,1, '普通插话不能关闭信号');
appendFileSync(join(root,'maker.inbox'),JSON.stringify({type:'say',askId:'a',at:'2026-01-01T00:00:02.000Z'})+'\n');
assert.equal(pendingFor('maker').length,0, '只有关联 ID 答复才关闭');
const review = {...ask,id:'b',kind:'review'};
appendFileSync(join(root,'maker.asks'),JSON.stringify(review)+'\n');
assert.equal(pendingFor('maker').length,1);
assert.equal(await localCondition('review',{id:'maker',entry:{at:Date.now()},cwd:root}),null);
assert.equal(await localCondition('run:later',{id:'maker',entry:{at:Date.now()},cwd:root}),null);
put('review.brief.json',{review:true,for:'work'});
put('review.json',{detach:true,runId:'review',name:'later',briefPath:join(root,'review.brief.md'),startedAt:'2026-01-01T00:00:02.000Z',status:'running'});
assert.equal(linkedReview(review,maker).runId,'review');
assert.equal(pendingFor('maker').length,0);
assert.equal(await localCondition('run:later',{id:'maker',entry:{at:Date.now()},cwd:root}),null);
put('review.json',{detach:true,runId:'review',name:'later',briefPath:join(root,'review.brief.md'),startedAt:'2026-01-01T00:00:02.000Z',status:'done'});
assert.equal((await localCondition('review',{id:'maker',entry:{at:Date.now()},cwd:root})).status,'done');
put('other.json',{detach:true,runId:'other',name:'later',status:'done'});
assert.equal((await localCondition('run:later',{id:'maker',entry:{at:Date.now()},cwd:root})).status,'failed', 'ambiguous names remain rejected');
rmSync(join(root,'other.json'));
assert.equal((await localCondition('run:later',{id:'maker',entry:{at:Date.now()},cwd:root})).status,'done', 'deletions invalidate cached records');
put('review.json',{detach:true,runId:'review',name:'later',status:'running'});
assert.equal(await localCondition('run:later',{id:'maker',entry:{at:Date.now()},cwd:root}),null, 'updates invalidate cached records');
assert.equal(records().some(r=>r.runId==='other'),false);
rmSync(root,{recursive:true,force:true});
console.log('requests tests passed');
